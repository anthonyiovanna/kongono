<?php

declare(strict_types=1);

namespace Kongono\DatabaseMapping\Diagnostic;

use Kongono\ApiMetadata\Api;
use Kongono\ApiMetadata\ApiStatus;
use Kongono\Diagnostics\Context\DiagnosticContext;
use Kongono\Diagnostics\Context\DiagnosticContextSchema;
use Kongono\Diagnostics\Context\DiagnosticDisclosure;
use Kongono\Diagnostics\Context\DiagnosticFieldSchema;
use Kongono\Diagnostics\Context\DiagnosticValueKind;

/** Owns the closed non-disclosing Phase 6F diagnostic contract. */
#[Api(ApiStatus::Internal)]
enum MappingDiagnostic: string
{
    case InvalidMappingSource = 'KGN-MAPPING-1001';
    case InvalidMappingArtifact = 'KGN-MAPPING-1002';
    case StaleMappingArtifact = 'KGN-MAPPING-1003';
    case InvalidGeneratedDataAccess = 'KGN-MAPPING-1004';
    case GeneratedPublicationFailed = 'KGN-MAPPING-1005';
    case HydrationFailed = 'KGN-MAPPING-1006';
    case RowCardinalityInvalid = 'KGN-MAPPING-1007';
    case RepositoryExecutionFailed = 'KGN-MAPPING-1008';
    case RepositoryCleanupFailed = 'KGN-MAPPING-1009';

    public function context(
        string $failureCategory,
        int $ordinal = 0,
        int $count = 0,
        bool $artifactCurrent = false,
        string $operationKind = 'build',
        bool $cleanupEvidence = false,
    ): DiagnosticContext {
        return new DiagnosticContext(new DiagnosticContextSchema(
            $this->operation(),
            $this->violatedInvariant(),
            [
                new DiagnosticFieldSchema('schema_version', 'Schema version', DiagnosticValueKind::Integer, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('failure_category', 'Failure category', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('ordinal', 'Ordinal', DiagnosticValueKind::Integer, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('count', 'Count', DiagnosticValueKind::Integer, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('artifact_current', 'Artifact current', DiagnosticValueKind::Boolean, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('operation_kind', 'Operation kind', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('cleanup_evidence', 'Cleanup evidence', DiagnosticValueKind::Boolean, DiagnosticDisclosure::Safe),
            ],
        ), [
            'schema_version' => 1,
            'failure_category' => $failureCategory,
            'ordinal' => max(0, $ordinal),
            'count' => max(0, $count),
            'artifact_current' => $artifactCurrent,
            'operation_kind' => $operationKind,
            'cleanup_evidence' => $cleanupEvidence,
        ]);
    }

    public function operation(): string
    {
        return match ($this) {
            self::InvalidMappingSource => 'Validate mapping source',
            self::InvalidMappingArtifact => 'Validate mapping artifact',
            self::StaleMappingArtifact => 'Match mapping artifact to current state',
            self::InvalidGeneratedDataAccess => 'Validate generated data access',
            self::GeneratedPublicationFailed => 'Publish generated data access',
            self::HydrationFailed => 'Hydrate mapped record',
            self::RowCardinalityInvalid => 'Enforce repository row cardinality',
            self::RepositoryExecutionFailed => 'Execute generated repository operation',
            self::RepositoryCleanupFailed => 'Complete repository stream cleanup',
        };
    }

    public function violatedInvariant(): string
    {
        return match ($this) {
            self::InvalidMappingSource => 'The explicit source and record contracts must satisfy the closed version-1 mapping vocabulary',
            self::InvalidMappingArtifact => 'The mapping artifact must be canonical and internally provenance-consistent',
            self::StaleMappingArtifact => 'The artifact must equal a complete build from exact current evidence',
            self::InvalidGeneratedDataAccess => 'Generated PHP must be canonical, bounded, structural, and current',
            self::GeneratedPublicationFailed => 'Generated bytes must publish atomically without overwrite or residue',
            self::HydrationFailed => 'Rows must match exact generated ordinals, aliases, kinds, nullability, and scalar types',
            self::RowCardinalityInvalid => 'A generated find operation must observe at most one mapped row',
            self::RepositoryExecutionFailed => 'A generated repository must receive the exact expected neutral result shape',
            self::RepositoryCleanupFailed => 'Primary and cleanup failures must remain exact and deterministically ordered',
        };
    }

    public function title(): string
    {
        return match ($this) {
            self::InvalidMappingSource => 'Invalid mapping source',
            self::InvalidMappingArtifact => 'Invalid mapping artifact',
            self::StaleMappingArtifact => 'Stale mapping artifact',
            self::InvalidGeneratedDataAccess => 'Invalid generated data access',
            self::GeneratedPublicationFailed => 'Generated data-access publication failed',
            self::HydrationFailed => 'Mapped record hydration failed',
            self::RowCardinalityInvalid => 'Repository row cardinality invalid',
            self::RepositoryExecutionFailed => 'Repository execution failed',
            self::RepositoryCleanupFailed => 'Repository cleanup failed',
        };
    }

    public function remediation(): string
    {
        return match ($this) {
            self::InvalidMappingSource => 'Correct the explicit source or record declaration and rebuild',
            self::InvalidMappingArtifact => 'Regenerate the artifact with the supported mapping builder',
            self::StaleMappingArtifact => 'Build a new artifact from the exact current application state',
            self::InvalidGeneratedDataAccess => 'Regenerate data access from the exact current mapping artifact',
            self::GeneratedPublicationFailed => 'Use a safe output directory and resolve the publication conflict',
            self::HydrationFailed => 'Correct the row shape or mapping before hydrating the record',
            self::RowCardinalityInvalid => 'Restore uniqueness for the mapped identity before retrying',
            self::RepositoryExecutionFailed => 'Use an executor and compiler that return the required neutral result type',
            self::RepositoryCleanupFailed => 'Inspect retained failure identities and retire uncertain provider state',
        };
    }
}
