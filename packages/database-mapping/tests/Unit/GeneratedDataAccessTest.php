<?php

declare(strict_types=1);

namespace Kongono\DatabaseMapping\Tests\Unit;

use Kongono\Database\CommandResult;
use Kongono\Database\DatabaseColumn;
use Kongono\Database\DatabaseRow;
use Kongono\Database\DatabaseValue;
use Kongono\DatabaseMapping\Build\MappingArtifactBuilder;
use Kongono\DatabaseMapping\Exception\GeneratedDataAccessPublicationException;
use Kongono\DatabaseMapping\Exception\HydrationException;
use Kongono\DatabaseMapping\Exception\InvalidGeneratedDataAccessException;
use Kongono\DatabaseMapping\Exception\RepositoryCleanupException;
use Kongono\DatabaseMapping\Exception\RowCardinalityException;
use Kongono\DatabaseMapping\Generated\GeneratedDataAccessGenerator;
use Kongono\DatabaseMapping\Generated\GeneratedDataAccessPublisher;
use Kongono\DatabaseMapping\Generated\GeneratedDataAccessValidator;
use Kongono\DatabaseMapping\Tests\Fixture\AccessorLog;
use Kongono\DatabaseMapping\Tests\Fixture\AllKindsRecord;
use Kongono\DatabaseMapping\Tests\Fixture\MemoryRowStream;
use Kongono\DatabaseMapping\Tests\Fixture\QueueExecutor;
use Kongono\DatabaseMapping\Tests\Fixture\RecordingCompiler;
use Kongono\DatabaseSql\DeletePlan;
use Kongono\DatabaseSql\InsertPlan;
use Kongono\DatabaseSql\SelectPlan;
use Kongono\DatabaseSql\UpdatePlan;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunInSeparateProcess;
use PHPUnit\Framework\TestCase;
use ReflectionClass;
use ReflectionMethod;
use RuntimeException;

final class GeneratedDataAccessTest extends TestCase
{
    private const SOURCE = 'packages/database-mapping/tests/Fixture/kongono.data-mapping.json';
    private const NAMESPACE = 'Kongono\\DatabaseMapping\\Tests\\Generated';

    #[RunInSeparateProcess]
    #[PreserveGlobalState(false)]
    public function testGeneratedOutputIsCurrentPublishableExecutableAndExact(): void
    {
        $root = dirname(__DIR__, 4);
        $builder = new MappingArtifactBuilder();
        $artifact = $builder->build($root, self::SOURCE);
        $generator = new GeneratedDataAccessGenerator();
        $first = $generator->generate($root, self::SOURCE, $artifact->canonicalBytes());
        $second = $generator->generate($root, self::SOURCE, $artifact->canonicalBytes());
        self::assertSame($first->canonicalBytes(), $second->canonicalBytes());
        self::assertSame($first->generatedFileSha256(), $second->generatedFileSha256());
        self::assertStringNotContainsString('ReflectionClass', $first->canonicalBytes());
        self::assertStringNotContainsString('eval(', $first->canonicalBytes());
        self::assertStringNotContainsString('call_user_func', $first->canonicalBytes());

        $validator = new GeneratedDataAccessValidator();
        self::assertSame($first->generatedFileSha256(), $validator->validateStructure($first->canonicalBytes())->generatedFileSha256());
        self::assertSame($first->generatedFileSha256(), $validator->validateCurrent($root, self::SOURCE, $artifact->canonicalBytes(), $first->canonicalBytes())->generatedFileSha256());
        $tampered = str_replace('kongono.generated-data-access', 'kongono.generated-data-accesx', $first->canonicalBytes());
        try {
            $validator->validateStructure($tampered);
            self::fail('Tampered generated bytes were accepted.');
        } catch (InvalidGeneratedDataAccessException $exception) {
            self::assertSame('KGN-MAPPING-1004', $exception->diagnosticId());
        }

        $output = $this->temporaryDirectory('output');
        $collision = $this->temporaryDirectory('collision');
        try {
            $publisher = new GeneratedDataAccessPublisher();
            $path = $publisher->publish($first, $output);
            self::assertSame($path, $publisher->publish($first, $output));
            $collisionPath = $publisher->publish($first, $collision);
            file_put_contents($collisionPath, "conflict\n");
            try {
                $publisher->publish($first, $collision);
                self::fail('A generated publication collision was accepted.');
            } catch (GeneratedDataAccessPublicationException $exception) {
                self::assertSame('KGN-MAPPING-1005', $exception->diagnosticId());
            }

            require $path;
            $this->mapperBehavior();
            $this->repositoryFindBehavior();
            $this->repositoryMutationBehavior();
            $this->combinedFailureBehavior();
        } finally {
            $this->removeDirectory($output);
            $this->removeDirectory($collision);
        }
    }

    private function mapperBehavior(): void
    {
        $mapper = $this->generatedClass('AllKindsMapper')->newInstance();
        $hydrate = new ReflectionMethod($mapper, 'hydrate');
        $binary = "\0\xFFmapping";
        $row = $this->row([DatabaseValue::integer(7), DatabaseValue::boolean(true), DatabaseValue::float(1.5), DatabaseValue::null(), DatabaseValue::binary($binary)]);
        $record = $hydrate->invoke($mapper, $row);
        self::assertInstanceOf(AllKindsRecord::class, $record);

        AccessorLog::reset();
        $extract = new ReflectionMethod($mapper, 'extract');
        $values = $extract->invoke($mapper, new AllKindsRecord(7, true, 1.5, null, $binary));
        self::assertIsArray($values);
        $insert = $values['insert'] ?? null;
        $update = $values['update'] ?? null;
        self::assertIsArray($insert);
        self::assertIsArray($update);
        self::assertCount(5, $insert);
        self::assertCount(4, $update);
        self::assertSame(['id' => 1, 'active' => 1, 'score' => 1, 'name' => 1, 'payload' => 1], AccessorLog::counts());

        $sentinel = 'private_mapping_value';
        $wrong = new DatabaseRow(
            [new DatabaseColumn(0, $sentinel), new DatabaseColumn(1, 'kgn_f0001'), new DatabaseColumn(2, 'kgn_f0002'), new DatabaseColumn(3, 'kgn_f0003'), new DatabaseColumn(4, 'kgn_f0004')],
            [DatabaseValue::integer(7), DatabaseValue::boolean(true), DatabaseValue::float(1.5), DatabaseValue::null(), DatabaseValue::binary($binary)],
        );
        try {
            $hydrate->invoke($mapper, $wrong);
            self::fail('Wrong generated alias was accepted.');
        } catch (HydrationException $exception) {
            self::assertStringNotContainsString($sentinel, $exception->getMessage());
            self::assertStringNotContainsString($sentinel, (string) $exception);
        }
    }

    private function repositoryFindBehavior(): void
    {
        $columns = $this->columns();
        $none = new MemoryRowStream($columns, []);
        $one = new MemoryRowStream($columns, [$this->row([DatabaseValue::integer(7), DatabaseValue::boolean(true), DatabaseValue::float(1.5), DatabaseValue::text('one'), DatabaseValue::binary('x')])]);
        $two = new MemoryRowStream($columns, [
            $this->row([DatabaseValue::integer(7), DatabaseValue::boolean(true), DatabaseValue::float(1.5), DatabaseValue::text('one'), DatabaseValue::binary('x')]),
            $this->row([DatabaseValue::integer(7), DatabaseValue::boolean(false), DatabaseValue::float(2.5), DatabaseValue::text('two'), DatabaseValue::binary('y')]),
        ]);
        $executor = new QueueExecutor([$none, $one, $two]);
        $compiler = new RecordingCompiler();
        $repository = $this->generatedClass('AllKindsRepository')->newInstance($executor, $compiler);
        $find = new ReflectionMethod($repository, 'find');
        self::assertNull($find->invoke($repository, 7));
        self::assertInstanceOf(AllKindsRecord::class, $find->invoke($repository, 7));
        try {
            $find->invoke($repository, 7);
            self::fail('Two mapped rows were accepted.');
        } catch (RowCardinalityException $exception) {
            self::assertSame('KGN-MAPPING-1007', $exception->diagnosticId());
        }
        self::assertSame(1, $none->closeCount());
        self::assertSame(1, $one->closeCount());
        self::assertSame(1, $two->closeCount());
        self::assertCount(3, $compiler->plans());
        foreach ($compiler->plans() as $plan) {
            self::assertInstanceOf(SelectPlan::class, $plan);
            self::assertSame(2, $plan->limit());
            self::assertCount(5, $plan->projections());
        }
    }

    private function repositoryMutationBehavior(): void
    {
        $insert = new CommandResult(1);
        $update = new CommandResult(null);
        $delete = new CommandResult(0);
        $executor = new QueueExecutor([$insert, $update, $delete]);
        $compiler = new RecordingCompiler();
        $repository = $this->generatedClass('AllKindsRepository')->newInstance($executor, $compiler);
        $record = new AllKindsRecord(9, false, 2.5, 'mapped', 'binary');
        self::assertSame($insert, (new ReflectionMethod($repository, 'insert'))->invoke($repository, $record));
        self::assertSame($update, (new ReflectionMethod($repository, 'update'))->invoke($repository, $record));
        self::assertSame($delete, (new ReflectionMethod($repository, 'delete'))->invoke($repository, 9));
        [$insertPlan, $updatePlan, $deletePlan] = $compiler->plans();
        self::assertInstanceOf(InsertPlan::class, $insertPlan);
        self::assertCount(5, $insertPlan->assignments());
        self::assertSame([], $insertPlan->returning());
        self::assertInstanceOf(UpdatePlan::class, $updatePlan);
        self::assertCount(4, $updatePlan->assignments());
        self::assertFalse($updatePlan->scope()->isAllRows());
        self::assertSame([], $updatePlan->returning());
        self::assertInstanceOf(DeletePlan::class, $deletePlan);
        self::assertFalse($deletePlan->scope()->isAllRows());
        self::assertSame([], $deletePlan->returning());
    }

    private function combinedFailureBehavior(): void
    {
        $primary = new RuntimeException('native_primary_secret');
        $cleanup = new RuntimeException('native_cleanup_secret');
        $stream = new MemoryRowStream($this->columns(), [], $primary, $cleanup);
        $repository = $this->generatedClass('AllKindsRepository')->newInstance(
            new QueueExecutor([$stream]),
            new RecordingCompiler(),
        );
        try {
            (new ReflectionMethod($repository, 'find'))->invoke($repository, 1);
            self::fail('Combined repository failure was not reported.');
        } catch (RepositoryCleanupException $exception) {
            self::assertSame($primary, $exception->primaryFailure());
            self::assertSame([$cleanup], $exception->cleanupFailures());
            self::assertSame(1, $stream->closeCount());
            self::assertStringNotContainsString('native_primary_secret', (string) $exception);
            self::assertStringNotContainsString('native_cleanup_secret', $exception->getMessage());
        }
    }

    /** @param list<DatabaseValue> $values */
    private function row(array $values): DatabaseRow
    {
        return new DatabaseRow($this->columns(), $values);
    }

    /** @return list<DatabaseColumn> */
    private function columns(): array
    {
        return [
            new DatabaseColumn(0, 'kgn_f0000'),
            new DatabaseColumn(1, 'kgn_f0001'),
            new DatabaseColumn(2, 'kgn_f0002'),
            new DatabaseColumn(3, 'kgn_f0003'),
            new DatabaseColumn(4, 'kgn_f0004'),
        ];
    }

    private function temporaryDirectory(string $label): string
    {
        $path = str_replace('\\', '/', sys_get_temp_dir()) . '/kongono-mapping-' . $label . '-' . bin2hex(random_bytes(8));
        self::assertTrue(mkdir($path, 0o700, true));

        return $path;
    }

    /** @return ReflectionClass<object> */
    private function generatedClass(string $shortName): ReflectionClass
    {
        $name = self::NAMESPACE . '\\' . $shortName;
        if (!class_exists($name, false)) {
            throw new RuntimeException('Expected generated class is unavailable.');
        }

        return new ReflectionClass($name);
    }

    private function removeDirectory(string $path): void
    {
        if (!is_dir($path)) {
            return;
        }
        foreach (new \FilesystemIterator($path) as $item) {
            if ($item instanceof \SplFileInfo && $item->isFile()) {
                @unlink($item->getPathname());
            }
        }
        @rmdir($path);
    }
}
