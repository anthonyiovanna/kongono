<?php

declare(strict_types=1);

namespace Kongono\NetworkEgressApplication\Tests\Unit\Generated;

use Kongono\NetworkEgressApplication\Exception\InvalidGeneratedNetworkEgressWiringException;
use Kongono\NetworkEgressApplication\Exception\NetworkEgressWiringLoadException;
use Kongono\NetworkEgressApplication\Exception\NetworkEgressWiringPublicationException;
use Kongono\NetworkEgressApplication\Generated\NetworkEgressWiringGenerator;
use Kongono\NetworkEgressApplication\Generated\NetworkEgressWiringPublisher;
use Kongono\NetworkEgressApplication\Generated\NetworkEgressWiringValidator;
use Kongono\NetworkEgressApplication\Runtime\NetworkEgressWiringLoader;
use Kongono\NetworkEgressApplication\Tests\Support\NetworkEgressApplicationFactory;
use Kongono\NetworkEgressApplication\Tests\Support\RecordingResolver;
use Kongono\NetworkEgressApplication\Tests\Support\RecordingTransport;
use PHPUnit\Framework\TestCase;

final class NetworkEgressWiringTest extends TestCase
{
    public function testGenerationIsDeterministicCanonicalAndOmitsRawSensitiveValues(): void
    {
        $profile = NetworkEgressApplicationFactory::profile();
        $generator = new NetworkEgressWiringGenerator();
        $first = $generator->generate($profile);
        $second = $generator->generate($profile);

        self::assertSame($first->canonicalBytes(), $second->canonicalBytes());
        self::assertSame($first->generatedWiringSha256(), $second->generatedWiringSha256());
        self::assertStringStartsWith("<?php\n\ndeclare(strict_types=1);\n", $first->canonicalBytes());
        self::assertStringEndsWith("\n", $first->canonicalBytes());
        self::assertStringNotContainsString("\r", $first->canonicalBytes());
        self::assertStringNotContainsString('example.com', $first->canonicalBytes());
        self::assertStringNotContainsString('93.184.216.34', $first->canonicalBytes());
        self::assertStringNotContainsString($profile->artifact()->canonicalBytes(), $first->canonicalBytes());
    }

    public function testStructuralAndCurrentValidationRemainDistinctAndChangesFailClosed(): void
    {
        $profile = NetworkEgressApplicationFactory::profile();
        $bytes = (new NetworkEgressWiringGenerator())->generate($profile)->canonicalBytes();
        $validator = new NetworkEgressWiringValidator();
        self::assertSame($bytes, $validator->validateStructure($bytes)->canonicalBytes());

        foreach ([substr($bytes, 0, -1), str_replace('"generator_implementation_sha256":"', '"generator_implementation_sha256":"0', $bytes)] as $changed) {
            try {
                $validator->validateStructure($changed);
                self::fail('Changed generated bytes must fail structural validation.');
            } catch (InvalidGeneratedNetworkEgressWiringException $failure) {
                self::assertSame('KGN-NET-1541', $failure->diagnosticId());
            }
        }

        $this->expectException(InvalidGeneratedNetworkEgressWiringException::class);
        $validator->validateCurrent(NetworkEgressApplicationFactory::profile(NetworkEgressApplicationFactory::policy('other-policy')), $bytes);
    }

    public function testPublicationIsContainedIdempotentNoClobberAndLoadingIsInertUntilOneStart(): void
    {
        [$root, $output] = self::temporaryRoot();
        $profile = NetworkEgressApplicationFactory::profile();
        $wiring = NetworkEgressApplicationFactory::wiring($profile);
        $publisher = new NetworkEgressWiringPublisher();
        $path = $publisher->publish($root, 'generated', $wiring);
        self::assertSame($path, $publisher->publish($root, 'generated', $wiring));
        $loaded = (new NetworkEgressWiringLoader())->load($root, $profile, $path);
        $resolver = new RecordingResolver(NetworkEgressApplicationFactory::resolution());
        $transport = new RecordingTransport([NetworkEgressApplicationFactory::capabilities()], NetworkEgressApplicationFactory::session());
        self::assertSame(0, $resolver->calls);
        self::assertSame(0, $transport->openCalls);
        self::assertSame($profile, $loaded->start($resolver, $transport)->profile());
        self::assertSame(0, $resolver->calls);
        self::assertSame(0, $transport->openCalls);

        try {
            $loaded->start($resolver, $transport);
            self::fail('Loaded handle must permit one start only.');
        } catch (NetworkEgressWiringLoadException $failure) {
            self::assertSame('KGN-NET-1543', $failure->diagnosticId());
        } finally {
            @unlink($path);
            @rmdir($output);
            @rmdir($root);
        }
    }

    public function testPublicationRejectsInvalidRelativePathsAndPreservesConflict(): void
    {
        [$root, $output] = self::temporaryRoot();
        $wiring = NetworkEgressApplicationFactory::wiring();
        foreach (['', $output, 'C:generated', '../generated', 'generated/../elsewhere'] as $invalid) {
            try {
                (new NetworkEgressWiringPublisher())->publish($root, $invalid, $wiring);
                self::fail('Invalid relative output must fail.');
            } catch (NetworkEgressWiringPublicationException) {
                self::assertDirectoryExists($output);
            }
        }
        $path = $output . '/kongono-network-egress-wiring-v1-' . $wiring->generatedWiringSha256() . '.php';
        file_put_contents($path, 'conflict');
        try {
            (new NetworkEgressWiringPublisher())->publish($root, 'generated', $wiring);
            self::fail('Conflicting target must fail.');
        } catch (NetworkEgressWiringPublicationException) {
            self::assertSame('conflict', file_get_contents($path));
        } finally {
            @unlink($path);
            @rmdir($output);
            @rmdir($root);
        }
    }

    /** @return array{string,string} */
    private static function temporaryRoot(): array
    {
        $root = str_replace('\\', '/', sys_get_temp_dir() . '/kongono-egress-application-' . bin2hex(random_bytes(8)));
        $output = $root . '/generated';
        self::assertTrue(mkdir($root));
        self::assertTrue(mkdir($output));

        return [$root, $output];
    }
}
