<?php

declare(strict_types=1);

namespace Kongono\ExtensionComposition\Diagnostic;

use Kongono\ApiMetadata\Api;
use Kongono\ApiMetadata\ApiStatus;
use Kongono\Diagnostics\Context\DiagnosticContext;
use Kongono\Diagnostics\Context\DiagnosticContextSchema;
use Kongono\Diagnostics\Context\DiagnosticDisclosure;
use Kongono\Diagnostics\Context\DiagnosticFieldSchema;
use Kongono\Diagnostics\Context\DiagnosticValueKind;

/** Owns the fixed non-disclosing diagnostic for extension grant and wiring failures. */
#[Api(ApiStatus::Internal)]
enum ExtensionCompositionDiagnostic: string
{
    case CompositionFailed = 'KGN-EXTENSION-COMPOSITION-1201';

    public function contextSchema(): DiagnosticContextSchema
    {
        return new DiagnosticContextSchema(
            'Validate or publish trusted extension wiring',
            'Admission, grants, exact constructors, generated bytes, and publication must remain exact',
            [
                new DiagnosticFieldSchema('violation', 'Violation', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
                new DiagnosticFieldSchema('entry_count', 'Entry count', DiagnosticValueKind::Integer, DiagnosticDisclosure::Safe, false),
                new DiagnosticFieldSchema('entry_position', 'Entry position', DiagnosticValueKind::Integer, DiagnosticDisclosure::Protected, false),
            ],
        );
    }

    /** @param array<string, string|int|bool> $values */
    public function context(array $values): DiagnosticContext
    {
        return new DiagnosticContext($this->contextSchema(), $values);
    }
    public function title(): string
    {
        return 'Extension capability grant or generated wiring is invalid';
    }
    public function remediation(): string
    {
        return 'Supply exact current admitted trusted extensions, explicit decisions, typed providers, and a safe publication target';
    }
}
