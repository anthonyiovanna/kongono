<?php

declare(strict_types=1);

namespace Kongono\ExtensionComposition\Tests\Unit\Generated;

use Kongono\ExtensionAdmission\Admission\ExtensionAdmissionBuilder;
use Kongono\ExtensionAdmission\Selection\ExtensionAdmissionPlan;
use Kongono\ExtensionBuild\Artifact\ExtensionDeclarationArtifactBuilder;
use Kongono\ExtensionComposition\Exception\InvalidGeneratedExtensionWiringException;
use Kongono\ExtensionComposition\Generated\ExtensionWiringGenerator;
use Kongono\ExtensionComposition\Generated\ExtensionWiringValidator;
use Kongono\ExtensionComposition\Plan\ExtensionGrantPlan;
use PHPUnit\Framework\TestCase;

final class ExtensionWiringValidationTest extends TestCase
{
    public function testStructuralAndExactCurrentValidationReturnDetachedEvidence(): void
    {
        [$declarations, $admission, $plan] = self::scenario();
        $artifact = (new ExtensionWiringGenerator())->generate($declarations, $admission, $plan);
        $validator = new ExtensionWiringValidator();
        self::assertSame($artifact->wiringSha256(), $validator->validateStructure($artifact->canonicalBytes())->wiringSha256());
        self::assertSame($artifact->wiringSha256(), $validator->validateCurrent($declarations, $admission, $plan, $artifact->canonicalBytes())->wiringSha256());
    }

    public function testMalformedStaleOversizedAndForbiddenBytesFailWithoutLoading(): void
    {
        [$declarations, $admission, $plan] = self::scenario();
        $artifact = (new ExtensionWiringGenerator())->generate($declarations, $admission, $plan);
        $bytes = $artifact->canonicalBytes();
        $wrongNamespace = 'KongonoGenerated\\Extension\\V1\\A' . str_repeat('0', 64);
        $cases = [
            "\xEF\xBB\xBF" . $bytes,
            str_replace('return new self();', "eval('x');\n        return new self();", $bytes),
            str_replace('return new self();', "file_put_contents('private', 'value');\n        return new self();", $bytes),
            str_replace($artifact->generatedNamespace(), $wrongNamespace, $bytes),
            str_replace('"implementation_count":0', '"implementation_count":65', $bytes),
            str_replace('"application_provider_count":0', '"application_provider_count":1', $bytes),
            str_repeat('x', ExtensionWiringGenerator::MAX_GENERATED_BYTES + 1),
        ];
        foreach ($cases as $case) {
            try {
                (new ExtensionWiringValidator())->validateStructure($case);
                self::fail('Malformed generated bytes were accepted.');
            } catch (InvalidGeneratedExtensionWiringException $exception) {
                self::assertSame('KGN-EXTENSION-COMPOSITION-1201', $exception->diagnosticId());
            }
        }

        $stalePlan = new ExtensionGrantPlan(new \Kongono\ExtensionAdmission\Identity\AdmissionIdentity(str_repeat('f', 64)), [], []);
        try {
            (new ExtensionWiringValidator())->validateCurrent($declarations, $admission, $stalePlan, $bytes);
            self::fail('Stale current inputs were accepted.');
        } catch (InvalidGeneratedExtensionWiringException $exception) {
            self::assertSame('KGN-EXTENSION-COMPOSITION-1201', $exception->diagnosticId());
        }
    }

    /** @return array{array{}, \Kongono\ExtensionAdmission\Admission\AdmittedExtensionGraphInput, ExtensionGrantPlan} */
    private static function scenario(): array
    {
        $declarations = [];
        $identity = (new ExtensionDeclarationArtifactBuilder())->build($declarations)->declarationSetIdentity();
        $admission = (new ExtensionAdmissionBuilder())->build($declarations, new ExtensionAdmissionPlan($identity, [], []), []);
        return [$declarations, $admission, new ExtensionGrantPlan($admission->admissionIdentity(), [], [])];
    }
}
