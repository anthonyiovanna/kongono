<?php

declare(strict_types=1);

namespace Kongono\AgentApplication\Tests\Unit\Generated;

use Kongono\AgentApplication\Exception\AgentWiringLoadException;
use Kongono\AgentApplication\Exception\AgentWiringPublicationException;
use Kongono\AgentApplication\Exception\InvalidGeneratedAgentWiringException;
use Kongono\AgentApplication\Generated\AgentWiringGenerator;
use Kongono\AgentApplication\Generated\AgentWiringPublisher;
use Kongono\AgentApplication\Generated\AgentWiringValidator;
use Kongono\AgentApplication\Runtime\AgentWiringLoader;
use Kongono\AgentApplication\Tests\Support\AgentApplicationFactory;
use PHPUnit\Framework\TestCase;

final class AgentWiringTest extends TestCase
{
    public function testGenerationIsDeterministicCanonicalBoundedAndNonDisclosing(): void
    {
        $profile = AgentApplicationFactory::profile();
        $generator = new AgentWiringGenerator();
        $first = $generator->generate($profile);
        $second = $generator->generate($profile);

        self::assertSame($first->canonicalBytes(), $second->canonicalBytes());
        self::assertSame($first->generatedWiringSha256(), $second->generatedWiringSha256());
        self::assertLessThanOrEqual(1_048_576, strlen($first->canonicalBytes()));
        self::assertStringStartsWith("<?php\n\ndeclare(strict_types=1);\n", $first->canonicalBytes());
        self::assertStringNotContainsString("\r", $first->canonicalBytes());
        self::assertFalse(str_starts_with($first->canonicalBytes(), "\xEF\xBB\xBF"));
        self::assertStringNotContainsString($profile->declarationArtifact()->canonicalBytes(), $first->canonicalBytes());
        self::assertStringNotContainsString('policy.primary', $first->canonicalBytes());
    }

    public function testStructuralAndExactCurrentValidationRejectMutationAndWrongProfile(): void
    {
        $profile = AgentApplicationFactory::profile();
        $bytes = (new AgentWiringGenerator())->generate($profile)->canonicalBytes();
        $validator = new AgentWiringValidator();

        foreach ([substr($bytes, 0, -1), $bytes . "\n", preg_replace('/"version":1/', '"version":2', $bytes, 1) ?? ''] as $invalid) {
            try {
                $validator->validateStructure($invalid);
                self::fail('Mutated generated bytes must fail.');
            } catch (InvalidGeneratedAgentWiringException $failure) {
                self::assertSame('KGN-AGENT-APPLICATION-1341', $failure->diagnosticId());
            }
        }

        $this->expectException(InvalidGeneratedAgentWiringException::class);
        $validator->validateCurrent(AgentApplicationFactory::profile('calendar.write'), $bytes);
    }

    public function testPublicationIsIdempotentNoClobberAndLoadingStartsOnce(): void
    {
        [$root, $output] = self::temporaryRoot();
        $profile = AgentApplicationFactory::profile('calendar.loader');
        $wiring = (new AgentWiringGenerator())->generate($profile);
        $publisher = new AgentWiringPublisher();
        $path = $publisher->publish($root, $output, $wiring);
        self::assertSame($path, $publisher->publish($root, $output, $wiring));

        $loaded = (new AgentWiringLoader())->load($root, $profile, $path);
        try {
            (new AgentWiringLoader())->load($root, $profile, $path);
            self::fail('A generated class collision must fail.');
        } catch (AgentWiringLoadException $failure) {
            self::assertSame('KGN-AGENT-APPLICATION-1343', $failure->diagnosticId());
        }
        $application = $loaded->start();
        self::assertSame($profile, $application->profile());
        $this->expectException(AgentWiringLoadException::class);
        try {
            $loaded->start();
        } finally {
            @unlink($path);
            @rmdir($output);
            @rmdir($root);
        }
    }

    public function testPublicationRejectsRootEqualAndExistingConflict(): void
    {
        [$root, $output] = self::temporaryRoot();
        $wiring = AgentApplicationFactory::wiring('calendar.conflict');
        $publisher = new AgentWiringPublisher();
        try {
            $publisher->publish($root, $root, $wiring);
            self::fail('Root-equal output must fail.');
        } catch (AgentWiringPublicationException $failure) {
            self::assertSame('KGN-AGENT-APPLICATION-1342', $failure->diagnosticId());
        }
        $path = $output . '/kongono-agent-wiring-v1-' . $wiring->generatedWiringSha256() . '.php';
        file_put_contents($path, 'conflict');
        try {
            $publisher->publish($root, $output, $wiring);
            self::fail('Conflicting target must fail.');
        } catch (AgentWiringPublicationException $failure) {
            self::assertSame('KGN-AGENT-APPLICATION-1342', $failure->diagnosticId());
        } finally {
            @unlink($path);
            @rmdir($output);
            @rmdir($root);
        }
    }

    /** @return array{string,string} */
    private static function temporaryRoot(): array
    {
        $root = str_replace('\\', '/', sys_get_temp_dir() . '/kongono-agent-application-' . bin2hex(random_bytes(8)));
        $output = $root . '/generated';
        self::assertTrue(mkdir($root));
        self::assertTrue(mkdir($output));

        return [$root, $output];
    }
}
