<?php

declare(strict_types=1);

namespace Kongono\AgentApplication\Diagnostic;

use Kongono\ApiMetadata\Api;
use Kongono\ApiMetadata\ApiStatus;
use Kongono\Diagnostics\Context\DiagnosticContext;
use Kongono\Diagnostics\Context\DiagnosticContextSchema;
use Kongono\Diagnostics\Context\DiagnosticDisclosure;
use Kongono\Diagnostics\Context\DiagnosticFieldSchema;
use Kongono\Diagnostics\Context\DiagnosticValueKind;

/** Owns the fixed non-disclosing Phase 13F diagnostic vocabulary. */
#[Api(ApiStatus::Internal)]
enum AgentApplicationDiagnostic: string
{
    case InvalidProfile = 'KGN-AGENT-APPLICATION-1340';
    case InvalidGeneratedWiring = 'KGN-AGENT-APPLICATION-1341';
    case PublicationFailed = 'KGN-AGENT-APPLICATION-1342';
    case LoadFailed = 'KGN-AGENT-APPLICATION-1343';
    case WorkflowFailed = 'KGN-AGENT-APPLICATION-1344';
    case LifecycleFailed = 'KGN-AGENT-APPLICATION-1345';

    public function contextSchema(): DiagnosticContextSchema
    {
        $field = match ($this) {
            self::InvalidProfile, self::InvalidGeneratedWiring => new DiagnosticFieldSchema('violation', 'Violation', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
            self::PublicationFailed, self::LoadFailed, self::WorkflowFailed, self::LifecycleFailed => new DiagnosticFieldSchema('stage', 'Stage', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
        };

        return new DiagnosticContextSchema($this->operation(), $this->invariant(), [$field]);
    }

    /** @param array<string, string|int|bool> $values */
    public function context(array $values): DiagnosticContext
    {
        return new DiagnosticContext($this->contextSchema(), $values);
    }

    public function title(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Agent Application profile is invalid',
            self::InvalidGeneratedWiring => 'Agent Application generated wiring is invalid',
            self::PublicationFailed => 'Agent Application wiring publication failed',
            self::LoadFailed => 'Agent Application wiring load failed',
            self::WorkflowFailed => 'Agent Application build workflow failed',
            self::LifecycleFailed => 'Agent Application lifecycle failed',
        };
    }

    public function remediation(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Supply one exact current declaration artifact and exactly matching admitted authority plan',
            self::InvalidGeneratedWiring => 'Regenerate canonical wiring from the exact current profile',
            self::PublicationFailed => 'Use one contained existing application-owned output directory and preserve the conflicting target',
            self::LoadFailed => 'Load one exact current content-addressed generated file in a fresh process',
            self::WorkflowFailed => 'Rebuild from unchanged explicit inputs after inspecting the preserved failure',
            self::LifecycleFailed => 'Inspect the bounded lifecycle stage and every preserved cleanup failure',
        };
    }

    private function operation(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Bind Agent Application profile',
            self::InvalidGeneratedWiring => 'Validate Agent Application wiring',
            self::PublicationFailed => 'Publish Agent Application wiring',
            self::LoadFailed => 'Load Agent Application wiring',
            self::WorkflowFailed => 'Build Agent Application workflow',
            self::LifecycleFailed => 'Run Agent Application lifecycle',
        };
    }

    private function invariant(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Profile evidence must bind one declaration, artifact, and admitted plan exactly',
            self::InvalidGeneratedWiring => 'Generated bytes must be canonical, bounded, inert, and exact-current',
            self::PublicationFailed => 'Publication must be contained, atomic, initial-only, and no-clobber',
            self::LoadFailed => 'Loading must use one explicit unchanged exact-current path and fixed boundary shape',
            self::WorkflowFailed => 'Build and check must preserve exact input and output snapshots',
            self::LifecycleFailed => 'One operation owns explicit ports and transfers cleanup ownership exactly once',
        };
    }
}
