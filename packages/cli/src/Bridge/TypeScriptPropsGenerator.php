<?php

declare(strict_types=1);

namespace Kongono\Cli\Bridge;

use BackedEnum;
use ReflectionClass;
use ReflectionEnum;
use ReflectionNamedType;
use ReflectionProperty;
use ReflectionUnionType;

/**
 * Generates strict TypeScript `.d.ts` prop & enum definitions directly from PHP 8.5
 * `readonly` DTO classes and `BackedEnum`s for React, Vue, and Svelte Bridge frontends.
 */
final readonly class TypeScriptPropsGenerator
{
    /**
     * Compile a list of PHP DTO / BackedEnum class names into strict TypeScript declarations.
     *
     * @param list<class-string> $classes
     */
    public function generate(array $classes): string
    {
        $lines = [
            '// Generated by `kongo bridge:types` — Do not edit by hand.',
            '',
        ];

        $emitted = [];
        foreach ($classes as $className) {
            $this->emitType($className, $emitted, $lines);
        }

        return implode("\n", $lines);
    }

    /**
     * @param class-string         $className
     * @param array<string, true>  $emitted
     * @param list<string>         $lines
     */
    private function emitType(string $className, array &$emitted, array &$lines): void
    {
        if (isset($emitted[$className])) {
            return;
        }
        $emitted[$className] = true;

        if (is_subclass_of($className, BackedEnum::class)) {
            $enumRef = new ReflectionEnum($className);
            $short = $this->safeIdentifier($enumRef->getShortName());
            $literals = [];
            foreach ($className::cases() as $case) {
                $literals[] = is_int($case->value)
                    ? (string) $case->value
                    : "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $case->value) . "'";
            }
            $lines[] = sprintf('export type %s = %s;', $short, [] !== $literals ? implode(' | ', $literals) : 'never');
            $lines[] = '';

            return;
        }

        if (!class_exists($className)) {
            return;
        }

        $ref = new ReflectionClass($className);
        $short = $this->safeIdentifier($ref->getShortName());

        /** @var list<class-string> $referenced */
        $referenced = [];
        $propLines = [];

        foreach ($ref->getProperties(ReflectionProperty::IS_PUBLIC) as $prop) {
            if ($prop->isStatic()) {
                continue;
            }
            $tsType = $this->mapPropertyType($prop, $referenced);
            $propName = $this->safeIdentifier($prop->getName());
            $optional = $prop->hasDefaultValue() && null === $prop->getDefaultValue() ? '?' : '';
            $propLines[] = sprintf('  readonly %s%s: %s;', $propName, $optional, $tsType);
        }

        foreach ($referenced as $dep) {
            $this->emitType($dep, $emitted, $lines);
        }

        $lines[] = sprintf('export interface %s {', $short);
        foreach ($propLines as $pl) {
            $lines[] = $pl;
        }
        $lines[] = '}';
        $lines[] = '';
    }

    /**
     * @param list<class-string> $referenced
     */
    private function mapPropertyType(ReflectionProperty $prop, array &$referenced): string
    {
        $type = $prop->getType();
        if ($type instanceof ReflectionNamedType) {
            $mapped = $this->mapNamedType($type->getName(), $referenced);

            return $type->allowsNull() && 'null' !== $mapped ? $mapped . ' | null' : $mapped;
        }
        if ($type instanceof ReflectionUnionType) {
            $parts = [];
            foreach ($type->getTypes() as $sub) {
                if ($sub instanceof ReflectionNamedType) {
                    $parts[] = $this->mapNamedType($sub->getName(), $referenced);
                }
            }

            return [] !== $parts ? implode(' | ', array_values(array_unique($parts))) : 'unknown';
        }

        return 'unknown';
    }

    /**
     * @param list<class-string> $referenced
     */
    private function mapNamedType(string $name, array &$referenced): string
    {
        return match ($name) {
            'string' => 'string',
            'int', 'float' => 'number',
            'bool', 'true', 'false' => 'boolean',
            'null' => 'null',
            'array' => 'unknown[]',
            'mixed', 'object' => 'unknown',
            default => $this->mapClassOrEnum($name, $referenced),
        };
    }

    /**
     * @param list<class-string> $referenced
     */
    private function mapClassOrEnum(string $name, array &$referenced): string
    {
        if (class_exists($name) || is_subclass_of($name, BackedEnum::class)) {
            $referenced[] = $name;
            $parts = explode('\\', $name);

            return $this->safeIdentifier(end($parts));
        }

        return 'unknown';
    }

    private function safeIdentifier(string $raw): string
    {
        $clean = preg_replace('/[^a-zA-Z0-9_]/', '', $raw);

        return (is_string($clean) && '' !== $clean) ? $clean : 'UnknownType';
    }
}
