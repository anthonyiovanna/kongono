<?php

declare(strict_types=1);

namespace Kongono\Cli\Deploy;

use InvalidArgumentException;

/**
 * Generates zero-downtime FrankenPHP persistent-worker deployment artifacts
 * for any Ubuntu 24.04 VPS (Hetzner, DigitalOcean, Vultr, Linode, AWS EC2).
 */
final readonly class DeployBlueprintGenerator
{
    /**
     * @return array<string, string> Map of relative file path => contents
     */
    public function generate(
        string $slug,
        string $domain,
        string $gitRepo = 'https://github.com/your-org/your-app.git',
        string $gitBranch = 'main',
        string $serverIp = '203.0.113.10',
        bool $postgres = true,
        bool $redis = true,
        bool $worker = false,
        int $threads = 4,
    ): array {
        $safeThreads = max(1, $threads);
        $safeSlug = preg_replace('/[^a-z0-9-]+/', '-', strtolower(trim($slug)));
        $cleanSlug = (is_string($safeSlug) && '' !== trim($safeSlug, '-')) ? trim($safeSlug, '-') : 'kongono-app';

        $cleanDomain = $this->validateDomain($domain);
        $cleanRepo = $this->validateGitRepo($gitRepo);
        $cleanBranch = $this->validateGitBranch($gitBranch);
        $cleanIp = $this->validateServerIp($serverIp);

        return [
            'Dockerfile' => $this->dockerfile($safeThreads),
            '.dockerignore' => ".git\n.env\n.env.*\n!.env.example\n!.env.production.example\n/var\n/tests\n/vendor\n",
            'Caddyfile' => $this->caddyfile($cleanDomain, $safeThreads),
            'docker-compose.prod.yml' => $this->composeFile($cleanSlug, $cleanDomain, $postgres, $redis, $worker),
            'deploy/provision.sh' => $this->provisionScript($cleanSlug),
            'deploy/deploy.sh' => $this->deployScript($cleanSlug, $cleanDomain, $cleanRepo, $cleanBranch, $cleanIp),
            '.env.production.example' => $this->envExample($cleanSlug, $cleanDomain, $postgres, $redis),
        ];
    }

    private function validateDomain(string $domain): string
    {
        $clean = strtolower(trim($domain));
        if ('' === $clean || 1 !== preg_match('/\A[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)*(?::\d{1,5})?\z/', $clean)) {
            throw new InvalidArgumentException(sprintf('Unsafe deployment domain "%s" rejected.', $domain));
        }

        return $clean;
    }

    private function validateGitRepo(string $repo): string
    {
        $clean = trim($repo);
        if (
            '' === $clean
            || false !== strpbrk($clean, "\r\n\0\"'`$;|&<>()\\")
            || 1 !== preg_match('/\A(?:https?:\/\/[a-zA-Z0-9._-]+(?::\d{1,5})?\/[a-zA-Z0-9._\/-]+|git@[a-zA-Z0-9._-]+:[a-zA-Z0-9._\/-]+)\z/', $clean)
        ) {
            throw new InvalidArgumentException(sprintf('Unsafe Git repository URL "%s" rejected.', $repo));
        }

        return $clean;
    }

    private function validateGitBranch(string $branch): string
    {
        $clean = trim($branch);
        if ('' === $clean || str_starts_with($clean, '-') || str_contains($clean, '..') || 1 !== preg_match('/\A[a-zA-Z0-9._\/-]+\z/', $clean)) {
            throw new InvalidArgumentException(sprintf('Unsafe Git branch name "%s" rejected.', $branch));
        }

        return $clean;
    }

    private function validateServerIp(string $ip): string
    {
        $clean = trim($ip);
        if (false === filter_var($clean, FILTER_VALIDATE_IP) && 1 !== preg_match('/\A[a-zA-Z0-9.-]+\z/', $clean)) {
            throw new InvalidArgumentException(sprintf('Unsafe server IP or hostname "%s" rejected.', $ip));
        }

        return $clean;
    }

    private function dockerfile(int $threads): string
    {
        return <<<DOCKER
# Generated by `kongo deploy:init` — Hardened Non-Root PHP 8.5 FrankenPHP Persistent Worker
FROM dunglas/frankenphp:1-php8.5-alpine

WORKDIR /app

RUN install-php-extensions dom pdo_pgsql sodium opcache zip \\
    && adduser -D -u 10001 -H -s /sbin/nologin kongono \\
    && printf 'expose_php=Off\\nsession.upload_progress.enabled=Off\\nzend.exception_ignore_args=On\\nallow_url_include=Off\\ndisplay_errors=Off\\nlog_errors=On\\n' > /usr/local/etc/php/conf.d/99-kongono-security.ini

COPY composer.json composer.lock ./
RUN composer install --no-dev --optimize-autoloader --no-interaction --no-progress

COPY --chown=kongono:kongono . .
RUN mkdir -p /app/var/cache /app/var/storage /app/storage /data /config \\
    && chown -R kongono:kongono /app/var /app/storage /data /config

ENV APP_ENV=production \\
    APP_DEBUG=false \\
    SESSION_SECURE=true \\
    TRUSTED_PROXIES="" \\
    FRANKENPHP_NUM_THREADS={$threads} \\
    FRANKENPHP_CONFIG="worker ./public/worker.php"

USER kongono

HEALTHCHECK --interval=10s --timeout=3s --start-period=5s --retries=3 \\
  CMD curl -fsS http://127.0.0.1:8080/health || exit 1

EXPOSE 8080
DOCKER;
    }

    private function caddyfile(string $domain, int $threads): string
    {
        return <<<CADDY
{
    frankenphp {
        num_threads {$threads}
        worker {
            file /app/public/worker.php
            num {$threads}
        }
    }
    order php_server before file_server
}

:8080 {
    handle /health {
        root * /app/public
        php_server
    }
    respond 404
}

{$domain} {
    encode zstd br gzip
    request_body {
        max_size 10MB
    }
    root * /app/public
    php_server
    header {
        Strict-Transport-Security "max-age=31536000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        X-Frame-Options "DENY"
        Referrer-Policy "strict-origin-when-cross-origin"
        Permissions-Policy "camera=(), microphone=(), geolocation=()"
        -Server
        -X-Powered-By
    }
}
CADDY;
    }

    private function composeFile(string $slug, string $domain, bool $pg, bool $redis, bool $worker): string
    {
        $yaml = <<<YAML
services:
  web:
    build: .
    container_name: {$slug}_web
    restart: unless-stopped
    read_only: true
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    cap_add:
      - NET_BIND_SERVICE
    tmpfs:
      - /tmp:noexec,nosuid,size=64m
    env_file: .env.production
    environment:
      SERVER_NAME: "{$domain}"
    ports:
      - "80:80"
      - "443:443"
      - "443:443/udp"
    volumes:
      - caddy_data:/data
      - caddy_config:/config
      - app_storage:/app/var/storage
      - app_cache:/app/var/cache
      - app_runtime_storage:/app/storage
    networks:
      - kongono_edge

YAML;

        if ($worker) {
            $yaml .= <<<YAML
  worker:
    build: .
    container_name: {$slug}_worker
    restart: unless-stopped
    read_only: true
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    tmpfs:
      - /tmp:noexec,nosuid,size=64m
    env_file: .env.production
    command: ["php", "/app/vendor/bin/kongo", "work", "--daemon", "--max-jobs=50"]
    volumes:
      - app_storage:/app/var/storage
      - app_cache:/app/var/cache
      - app_runtime_storage:/app/storage
    networks:
      - kongono_edge

YAML;
        }

        if ($pg) {
            $yaml .= <<<YAML
  postgres:
    image: postgres:17-alpine
    container_name: {$slug}_postgres
    restart: unless-stopped
    security_opt:
      - no-new-privileges:true
    environment:
      POSTGRES_DB: {$slug}
      POSTGRES_USER: postgres
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD:?POSTGRES_PASSWORD must be set}
    volumes:
      - pg_data:/var/lib/postgresql/data
    networks:
      - kongono_edge

YAML;
        }

        if ($redis) {
            $yaml .= <<<YAML
  redis:
    image: redis:7-alpine
    container_name: {$slug}_redis
    restart: unless-stopped
    read_only: true
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    command: ["redis-server", "--appendonly", "yes", "--protected-mode", "yes", "--requirepass", "\${REDIS_PASSWORD:?REDIS_PASSWORD must be set}"]
    volumes:
      - redis_data:/data
    networks:
      - kongono_edge

YAML;
        }

        $yaml .= "volumes:\n  caddy_data:\n  caddy_config:\n  app_storage:\n  app_cache:\n  app_runtime_storage:\n";
        if ($pg) {
            $yaml .= "  pg_data:\n";
        }
        if ($redis) {
            $yaml .= "  redis_data:\n";
        }
        $yaml .= "\nnetworks:\n  kongono_edge:\n    external: true\n";

        return $yaml;
    }

    private function provisionScript(string $slug): string
    {
        return <<<SH
#!/usr/bin/env bash
# Generated by `kongo deploy:init` — Hardened Ubuntu 24.04 VPS Provisioner
set -euo pipefail

apt-get update -qq
DEBIAN_FRONTEND=noninteractive apt-get install -y -qq ca-certificates curl gnupg ufw fail2ban git unzip docker.io docker-compose-v2
systemctl enable --now docker

ufw default deny incoming
ufw default allow outgoing
ufw allow 22/tcp
ufw allow 80/tcp
ufw allow 443/tcp
ufw allow 443/udp
ufw --force enable

id -u deploy >/dev/null 2>&1 || useradd -m -s /bin/bash -G docker deploy
mkdir -p /srv/kongono/{$slug}/backups
chown -R deploy:deploy /srv/kongono
docker network inspect kongono_edge >/dev/null 2>&1 || docker network create kongono_edge
echo "VPS provisioned and ready for Kongono FrankenPHP zero-downtime deploys."
SH;
    }

    private function deployScript(string $slug, string $domain, string $repo, string $branch, string $ip): string
    {
        return <<<SH
#!/usr/bin/env bash
# Zero-downtime FrankenPHP deploy script for {$slug} ({$domain}) on {$ip}
# Usage:
#   DEPLOY_REF=<40-hex-commit-sha-or-release-tag> ./deploy.sh
#   ./deploy.sh <40-hex-commit-sha-or-release-tag>
#   VERIFY_SIGNATURES=1 ./deploy.sh v1.2.3
#   ALLOW_MUTABLE_BRANCH=1 ./deploy.sh {$branch}
set -euo pipefail

DEPLOY_REF="\${1:-\${DEPLOY_REF:-}}"
if [ -z "\${DEPLOY_REF}" ]; then
  echo "ERROR: Refusing to deploy an unpinned mutable branch tip." >&2
  echo "Pass an immutable 40-char commit SHA or release tag (e.g. DEPLOY_REF=<sha> ./deploy.sh)," >&2
  echo "or explicitly opt in with ALLOW_MUTABLE_BRANCH=1 DEPLOY_REF={$branch} ./deploy.sh." >&2
  exit 2
fi

if [[ "\${DEPLOY_REF}" == -* ]] || [[ ! "\${DEPLOY_REF}" =~ ^[A-Za-z0-9._/-]+$ ]]; then
  echo "ERROR: Invalid DEPLOY_REF format." >&2
  exit 2
fi

IS_IMMUTABLE_SHA=0
if [[ "\${DEPLOY_REF}" =~ ^[0-9a-f]{40}$ ]]; then
  IS_IMMUTABLE_SHA=1
fi

APP_DIR="/srv/kongono/{$slug}"
if [ ! -d "\${APP_DIR}/.git" ]; then
  git clone --no-checkout -- "{$repo}" "\${APP_DIR}"
fi
cd "\${APP_DIR}"

if [ "\${IS_IMMUTABLE_SHA}" -eq 1 ]; then
  git fetch --depth=1 origin "\${DEPLOY_REF}"
  RESOLVED_SHA="\$(git rev-parse --verify FETCH_HEAD^{commit})"
  if [ "\${RESOLVED_SHA}" != "\${DEPLOY_REF}" ]; then
    echo "ERROR: Fetched commit \${RESOLVED_SHA} does not match expected SHA \${DEPLOY_REF}." >&2
    exit 1
  fi
elif [ "\${ALLOW_MUTABLE_BRANCH:-0}" = "1" ]; then
  git fetch --depth=1 origin "refs/heads/\${DEPLOY_REF}"
  RESOLVED_SHA="\$(git rev-parse --verify FETCH_HEAD^{commit})"
else
  git fetch --depth=1 origin "refs/tags/\${DEPLOY_REF}:refs/tags/\${DEPLOY_REF}"
  RESOLVED_SHA="\$(git rev-parse --verify "refs/tags/\${DEPLOY_REF}^{commit}")"
fi

if [ "\${VERIFY_SIGNATURES:-0}" = "1" ]; then
  if [ "\${IS_IMMUTABLE_SHA}" -eq 1 ] || [ "\${ALLOW_MUTABLE_BRANCH:-0}" = "1" ]; then
    git verify-commit "\${RESOLVED_SHA}"
  else
    git verify-tag "\${DEPLOY_REF}"
  fi
fi

git checkout --detach --force "\${RESOLVED_SHA}"

docker compose -f docker-compose.prod.yml build --pull web
docker compose -f docker-compose.prod.yml up -d --remove-orphans

for i in 1 2 3 4 5; do
  if curl -fsS "https://{$domain}/health" >/dev/null 2>&1; then
    echo "Release \${RESOLVED_SHA} is LIVE at https://{$domain}"
    exit 0
  fi
  sleep 2
done
echo "Health check failed — inspect: docker logs {$slug}_web"
exit 1
SH;
    }

    private function envExample(string $slug, string $domain, bool $pg, bool $redis): string
    {
        $lines = [
            'APP_NAME="' . $slug . '"',
            'APP_ENV=production',
            'APP_DEBUG=false',
            'APP_URL=https://' . $domain,
            'SESSION_SECURE=true',
            '# Comma-separated reverse-proxy CIDRs/IPs allowed to supply X-Forwarded-* (leave empty if direct):',
            'TRUSTED_PROXIES=',
            'APP_KEY=REPLACE_WITH_kongo_key_generate',
        ];
        if ($pg) {
            $lines[] = 'POSTGRES_PASSWORD=CHANGE_ME';
            $lines[] = 'DATABASE_URL=pgsql://postgres:CHANGE_ME@' . $slug . '_postgres:5432/' . $slug . '?sslmode=prefer';
        }
        if ($redis) {
            $lines[] = 'REDIS_PASSWORD=CHANGE_ME';
            $lines[] = 'REDIS_URL=redis://:CHANGE_ME@' . $slug . '_redis:6379/0';
        }
        $lines[] = '# Optional S3-compatible object storage (AWS S3 / Cloudflare R2 / MinIO) for multi-node scale-out:';
        $lines[] = '# S3_BUCKET=';
        $lines[] = '# S3_REGION=us-east-1';
        $lines[] = '# S3_ENDPOINT=';
        $lines[] = '# S3_ACCESS_KEY_ID=';
        $lines[] = '# S3_SECRET_ACCESS_KEY=';

        return implode("\n", $lines) . "\n";
    }
}
