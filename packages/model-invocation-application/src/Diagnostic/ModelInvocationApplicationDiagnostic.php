<?php

declare(strict_types=1);

namespace Kongono\ModelInvocationApplication\Diagnostic;

use Kongono\ApiMetadata\Api;
use Kongono\ApiMetadata\ApiStatus;
use Kongono\Diagnostics\Context\DiagnosticContext;
use Kongono\Diagnostics\Context\DiagnosticContextSchema;
use Kongono\Diagnostics\Context\DiagnosticDisclosure;
use Kongono\Diagnostics\Context\DiagnosticFieldSchema;
use Kongono\Diagnostics\Context\DiagnosticValueKind;

/** Owns the closed non-disclosing Phase 14F diagnostic vocabulary. */
#[Api(ApiStatus::Internal)]
enum ModelInvocationApplicationDiagnostic: string
{
    case InvalidProfile = 'KGN-MODEL-APPLICATION-1430';
    case InvalidGeneratedWiring = 'KGN-MODEL-APPLICATION-1431';
    case PublicationFailed = 'KGN-MODEL-APPLICATION-1432';
    case LoadFailed = 'KGN-MODEL-APPLICATION-1433';
    case WorkflowFailed = 'KGN-MODEL-APPLICATION-1434';
    case LifecycleFailed = 'KGN-MODEL-APPLICATION-1435';
    case OperationFailed = 'KGN-MODEL-APPLICATION-1436';

    public function contextSchema(): DiagnosticContextSchema
    {
        $field = match ($this) {
            self::InvalidProfile, self::InvalidGeneratedWiring => new DiagnosticFieldSchema('violation', 'Violation', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
            self::PublicationFailed, self::LoadFailed, self::WorkflowFailed, self::LifecycleFailed, self::OperationFailed => new DiagnosticFieldSchema('stage', 'Stage', DiagnosticValueKind::Text, DiagnosticDisclosure::Safe),
        };

        return new DiagnosticContextSchema($this->operation(), $this->invariant(), [$field]);
    }

    /** @param array<string, string|int|bool> $values */
    public function context(array $values): DiagnosticContext
    {
        return new DiagnosticContext($this->contextSchema(), $values);
    }

    public function title(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Model Invocation Application profile is invalid',
            self::InvalidGeneratedWiring => 'Model Invocation Application generated wiring is invalid',
            self::PublicationFailed => 'Model Invocation Application wiring publication failed',
            self::LoadFailed => 'Model Invocation Application wiring load failed',
            self::WorkflowFailed => 'Model Invocation Application build workflow failed',
            self::LifecycleFailed => 'Model Invocation Application lifecycle failed',
            self::OperationFailed => 'Model Invocation Application operation failed',
        };
    }

    public function remediation(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Supply one exact current invocation-plan source and its exact artifact bytes',
            self::InvalidGeneratedWiring => 'Regenerate canonical wiring from the exact current application profile',
            self::PublicationFailed => 'Use one contained existing application-owned output directory and preserve any conflicting target',
            self::LoadFailed => 'Load one exact current content-addressed generated file in a fresh process',
            self::WorkflowFailed => 'Rebuild from unchanged explicit inputs after inspecting the preserved failure',
            self::LifecycleFailed => 'Create a fresh application instance and perform at most one terminal operation',
            self::OperationFailed => 'Inspect the bounded stage and preserve the underlying runtime evidence',
        };
    }

    private function operation(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Bind Model Invocation Application profile',
            self::InvalidGeneratedWiring => 'Validate Model Invocation Application wiring',
            self::PublicationFailed => 'Publish Model Invocation Application wiring',
            self::LoadFailed => 'Load Model Invocation Application wiring',
            self::WorkflowFailed => 'Build Model Invocation Application workflow',
            self::LifecycleFailed => 'Run Model Invocation Application lifecycle',
            self::OperationFailed => 'Construct Model Invocation Runtime request',
        };
    }

    private function invariant(): string
    {
        return match ($this) {
            self::InvalidProfile => 'Profile evidence must bind one exact source and exact-current artifact',
            self::InvalidGeneratedWiring => 'Generated bytes must be canonical, bounded, inert, and exact-current',
            self::PublicationFailed => 'Publication must be contained, atomic, initial-only, and no-clobber',
            self::LoadFailed => 'Loading must use one explicit unchanged exact-current path and fixed boundary shape',
            self::WorkflowFailed => 'Build and check must preserve exact input and output snapshots',
            self::LifecycleFailed => 'One application instance may perform at most one terminal synchronous operation',
            self::OperationFailed => 'Runtime request construction must preserve exact bound evidence and collaborators',
        };
    }
}
