<?php

declare(strict_types=1);

namespace Kongono\ModelInvocationApplication\Tests\Unit\Generated;

use Kongono\ModelInvocationApplication\Exception\InvalidGeneratedModelInvocationWiringException;
use Kongono\ModelInvocationApplication\Exception\ModelInvocationWiringLoadException;
use Kongono\ModelInvocationApplication\Exception\ModelInvocationWiringPublicationException;
use Kongono\ModelInvocationApplication\Generated\ModelInvocationWiringGenerator;
use Kongono\ModelInvocationApplication\Generated\ModelInvocationWiringPublisher;
use Kongono\ModelInvocationApplication\Generated\ModelInvocationWiringValidator;
use Kongono\ModelInvocationApplication\Runtime\ModelInvocationWiringLoader;
use Kongono\ModelInvocationApplication\Tests\Support\ModelInvocationApplicationFactory;
use Kongono\ModelInvocationApplication\Tests\Support\RecordingInvocationAdapter;
use Kongono\ModelInvocationApplication\Tests\Support\RecordingInvocationAdapterSession;
use Kongono\ModelInvocationBuild\Plan\AdapterIdentity;
use PHPUnit\Framework\TestCase;

final class ModelInvocationWiringTest extends TestCase
{
    public function testGenerationIsDeterministicCanonicalAndOmitsRawPrivateValues(): void
    {
        $secret = 'raw-private-message-and-credential';
        $profile = ModelInvocationApplicationFactory::profile(ModelInvocationApplicationFactory::source($secret));
        $generator = new ModelInvocationWiringGenerator();
        $first = $generator->generate($profile);
        $second = $generator->generate($profile);

        self::assertSame($first->canonicalBytes(), $second->canonicalBytes());
        self::assertSame($first->generatedWiringSha256(), $second->generatedWiringSha256());
        self::assertStringStartsWith("<?php\n\ndeclare(strict_types=1);\n", $first->canonicalBytes());
        self::assertStringNotContainsString("\r", $first->canonicalBytes());
        self::assertStringNotContainsString($secret, $first->canonicalBytes());
        self::assertStringNotContainsString($profile->artifact()->canonicalBytes(), $first->canonicalBytes());
    }

    public function testStructuralAndCurrentValidationRemainDistinctAndFailClosed(): void
    {
        $profile = ModelInvocationApplicationFactory::profile();
        $bytes = (new ModelInvocationWiringGenerator())->generate($profile)->canonicalBytes();
        $validator = new ModelInvocationWiringValidator();
        self::assertSame($bytes, $validator->validateStructure($bytes)->canonicalBytes());

        try {
            $validator->validateStructure(substr($bytes, 0, -1));
            self::fail('Mutated generated bytes must fail structural validation.');
        } catch (InvalidGeneratedModelInvocationWiringException $failure) {
            self::assertSame('KGN-MODEL-APPLICATION-1431', $failure->diagnosticId());
        }

        $this->expectException(InvalidGeneratedModelInvocationWiringException::class);
        $validator->validateCurrent(ModelInvocationApplicationFactory::profile(ModelInvocationApplicationFactory::source('other')), $bytes);
    }

    public function testPublicationIsContainedIdempotentNoClobberAndExplicitLoadingStartsOnce(): void
    {
        [$root, $output] = self::temporaryRoot();
        $profile = ModelInvocationApplicationFactory::profile();
        $wiring = ModelInvocationApplicationFactory::wiring($profile);
        $publisher = new ModelInvocationWiringPublisher();
        $path = $publisher->publish($root, $output, $wiring);
        self::assertSame($path, $publisher->publish($root, $output, $wiring));
        $loaded = (new ModelInvocationWiringLoader())->load($root, $profile, $path);
        $adapter = new RecordingInvocationAdapter(new AdapterIdentity('adapter.application'), new RecordingInvocationAdapterSession([]));
        self::assertSame($profile, $loaded->start($adapter)->profile());
        self::assertSame(0, $adapter->openCalls);

        try {
            $loaded->start($adapter);
            self::fail('Loaded handle must permit one start only.');
        } catch (ModelInvocationWiringLoadException $failure) {
            self::assertSame('KGN-MODEL-APPLICATION-1433', $failure->diagnosticId());
        } finally {
            @unlink($path);
            @rmdir($output);
            @rmdir($root);
        }
    }

    public function testPublicationRejectsRootEqualAndPreservesConflict(): void
    {
        [$root, $output] = self::temporaryRoot();
        $wiring = ModelInvocationApplicationFactory::wiring();
        try {
            (new ModelInvocationWiringPublisher())->publish($root, $root, $wiring);
            self::fail('Root-equal output must fail.');
        } catch (ModelInvocationWiringPublicationException) {
            self::assertDirectoryExists($output);
        }
        $path = $output . '/kongono-model-invocation-wiring-v1-' . $wiring->generatedWiringSha256() . '.php';
        file_put_contents($path, 'conflict');
        try {
            (new ModelInvocationWiringPublisher())->publish($root, $output, $wiring);
            self::fail('Conflicting target must fail.');
        } catch (ModelInvocationWiringPublicationException) {
            self::assertSame('conflict', file_get_contents($path));
        } finally {
            @unlink($path);
            @rmdir($output);
            @rmdir($root);
        }
    }

    /** @return array{string,string} */
    private static function temporaryRoot(): array
    {
        $root = str_replace('\\', '/', sys_get_temp_dir() . '/kongono-model-application-' . bin2hex(random_bytes(8)));
        $output = $root . '/generated';
        self::assertTrue(mkdir($root));
        self::assertTrue(mkdir($output));

        return [$root, $output];
    }
}
